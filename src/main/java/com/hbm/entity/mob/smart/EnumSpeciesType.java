package com.hbm.entity.mob.smart;

/**
 * Identify the 12 basic traits of a mob or NPC. Meant for more smart combat and building one's bestiary.<br>
 * (Stolen from Labyrinth of Touhou 2)
 * @author UFFR
 *
 */
public enum EnumSpeciesType
{
	/**Originates from a water environment**/
	AQUATIC,
	/**(Souped up) animal**/
	BEAST,
	/**Is a divine being**/
	DIVINE,
	/**Dragon or dragon-like, may also apply to reptillians in general**/
	DRAGON,
	/**Flying creature**/
	FLYING,
	/**Undead, non-corporeal usually**/
	GHOST,
	/**Has a humanoid shape**/
	HUMANOID,
	/**Is at least partially inorganic**/
	INORGANIC,
	/**Insect or insect-like**/
	INSECT,
	/**Oni or oni-related**/
	ONI,
	/**Has some notable trait that doesn't match any other category**/
	OTHER,
	/**Is a plant**/
	PLANT,
	/**Is a youkai**/
	YOUKAI;
}
